import Foundation

/// Окно ленты чата: сколько последних сообщений рисуется на экране и когда
/// дорисовывать следующие десять.
///
/// Владелец 08.11.2026: «у меня первично отображаются последние 10 сообщений,
/// при прокрутке происходит дозагруз… а сейчас что-то нет у этого дозагруза,
/// они просто как бы удалились».
///
/// Решение вынесено в чистую функцию, потому что раньше его принимал
/// `onAppear` однопиксельной полоски вверху ленты: лента с 07.11 — обычный
/// `VStack` (не ленивый), все строки монтируются сразу, полоска «появлялась»
/// ровно один раз при открытии в фазе `.idle`, и добавленный тогда же guard её
/// отбрасывал. Второй раз дозагруз не приходил никогда. Теперь решение
/// зависит только от геометрии прокрутки и состояния окна — и повторяется
/// столько раз, сколько владелец листает вверх.
enum RoleChatFeedWindow {
    /// Сколько сообщений дорисовывается за один долист вверх.
    static let step = 10

    /// Дорисовывать ли ещё `step` сообщений.
    /// - Parameters:
    ///   - hidden: сколько сообщений скрыто над окном (`count - window`).
    ///   - nearTop: верх содержимого близко к видимой области.
    ///   - scrolling: лента сейчас в движении от руки владельца.
    static func shouldGrow(hidden: Int, nearTop: Bool, scrolling: Bool) -> Bool {
        hidden > 0 && nearTop && scrolling
    }

    static func grown(window: Int) -> Int {
        window + step
    }
}
