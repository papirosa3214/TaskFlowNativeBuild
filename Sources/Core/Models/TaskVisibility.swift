import Foundation

/// Правила видимости задач (владелец, 01.11.2026).
///
/// «В архив уходят отменённые и выполненные, карточка одинаковая, единственная
/// пометка — отменённая либо выполненная. Из всех остальных списков убрать».
///
/// Поэтому в живых списках (Проекты, Сегодня, Ближайшие) закрытых задач нет, а
/// в архиве они лежат рядом с архивными — с тем же видом карточки.
enum TaskVisibility {
    /// Задача видна в живых списках: не архивная и не закрытая.
    static func isLive(_ task: ApiTask) -> Bool {
        !task.isArchived && task.status != .completed
    }

    /// Живые задачи из набора — корневые фильтрует вызывающий.
    static func liveTasks(_ tasks: [ApiTask]) -> [ApiTask] {
        tasks.filter { isLive($0) }
    }

    /// Закрытая карточка: выполнена — или отменена (в архиве, но выполнения
    /// не было). Единственная разница между двумя — пометка.
    static func isClosed(_ task: ApiTask) -> Bool {
        task.isArchived || task.status == .completed
    }

    /// Пометка результата в архивной карточке.
    static func outcomeLabel(_ task: ApiTask) -> String {
        task.status == .completed ? "Выполнена" : "Отменена"
    }
}
