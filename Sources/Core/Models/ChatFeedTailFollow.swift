import Foundation

/// Что лента делает, когда содержимое переписки меняется само: ответ роли
/// набегает, строка пересобирается и усыхает.
///
/// Инвариант: если пользователь был у хвоста переписки, после пересборки
/// содержимого он остаётся у хвоста. Иначе лента остаётся на старом
/// смещении, и получается ровно то, на что пожаловался владелец
/// (26.10.2026): под лентой пустота (содержимое уселось, а смещение прежнее),
/// а растущий ответ уходит под нижний край.
///
/// Смещение при пересборке не меняется само: SwiftUI держит его, а размер
/// содержимого — нет. Значит, возврат к хвосту нужно делать явно.
struct ChatFeedTailFollow: Equatable {
    /// Был ли пользователь у хвоста по последней геометрии.
    private(set) var wasAtTail: Bool = true

    /// Насколько ниже нижнего края экрана может уходить низ содержимого,
    /// чтобы это ещё считалось «у хвоста». Нужен запас: штатное состояние
    /// ленты — низ контента на десятки пунктов выше края.
    static let atTailTolerance: Double = 200

    /// Изменение высоты содержимого, начиная с которого пересборку видно.
    /// Меньшие колебания (layout «дышит» на пункт) трогать нельзя: лента
    /// дёргалась бы на каждом кадре.
    static let heightChangeThreshold: Double = 4

    init() {}

    /// Запомнить положение ленты по свежей геометрии.
    mutating func update(distanceToBottom: Double) {
        wasAtTail = distanceToBottom >= -Self.atTailTolerance
    }

    /// Нужно ли вернуть ленту к хвосту после изменения содержимого.
    static func needsCompensation(heightDelta: Double, wasAtTail: Bool) -> Bool {
        guard wasAtTail else { return false }
        return abs(heightDelta) >= heightChangeThreshold
    }

    /// Расстояние, на котором низ содержимого считается «у хвоста».
    ///
    /// Штатное состояние ленты: низ содержимого на 16 pt выше края области
    /// (нижний отступ safe area). Если лента остановилась ближе — она не
    /// доехала: контент пересобирался уже после прокрутки, и низ встал к
    /// самому краю, без отступа (владелец 26.10.2026).
    static let tailSeat: Double = -10

    /// Нужно ли доводить ленту до хвоста: пользователь был у хвоста, а лента
    /// встала выше него — значит, она туда не доехала.
    static func needsPullToTail(distanceToBottom: Double, wasAtTail: Bool) -> Bool {
        guard wasAtTail else { return false }
        return distanceToBottom > tailSeat
    }
}
