import Foundation

/// Политика слежения за хвостом переписки.
///
/// Один владелец положения ленты: решает, держим ли мы нижний край
/// переписки, когда содержимое растёт (новый ответ роли, индикатор
/// «печатает…», разворачивающийся блок).
///
/// Раньше решение принималось по `ScrollPosition.isPositionedByUser` — это
/// флаг SwiftUI, который ставится один раз и навсегда: после первого
/// прокручивания пользователем лента переставала следить за хвостом
/// навсегда (новые ответы не попадали в кадр — «прилипало»), а до первого
/// прокручивания любой рост высоты перетягивал всю ленту вниз («резко
/// уходило»). Флаг необратим и не отражает намерение пользователя прямо
/// сейчас: он не возвращается в «слежу», когда пользователь дочитывает
/// историю обратно к хвосту.
///
/// Политика явная и обратимая: слежение включено, пока пользователь в хвосте,
/// выключается, когда он ушёл читать историю, и возвращается, когда он
/// дошёл до хвоста сам или нажал «вниз».
///
/// Чистая логика без SwiftUI — проверяется обычными unit-тестами.
struct ChatTailPolicy: Equatable {
    /// События, меняющие решение о слежении за хвостом.
    enum Event: Equatable {
        /// Открыли чат: лента встаёт в хвост.
        case entered
        /// Пользователь сам довёл ленту: `nearBottom` — он у хвоста или нет.
        case userScrolled(nearBottom: Bool)
        /// Приложение само отправило ленту в хвост (отправка, кнопка «вниз»).
        case jumpedToTail
        /// Ленту подкрутили к конкретному сообщению (переход извне).
        case jumpedToMessage
    }

    /// Следим ли мы за хвостом переписки.
    private(set) var followsTail: Bool = true

    /// Учитывать ли пользовательское прокручивание.
    ///
    /// Пока пользователь ведёт ленту сам, расстояние до хвоста — это его
    /// намерение. Пока он не трогает ленту, рост содержимого не должен
    /// менять решение: иначе пришедший ответ роли утянул бы ленту вниз
    /// даже тогда, когда пользователь читает историю выше.
    private(set) var userDrivesScroll: Bool = false

    init() {}

    mutating func handle(_ event: Event) {
        switch event {
        case .entered:
            followsTail = true
            userDrivesScroll = false
        case .userScrolled(let nearBottom):
            followsTail = nearBottom
        case .jumpedToTail:
            followsTail = true
            userDrivesScroll = false
        case .jumpedToMessage:
            // Взгляд припаркован на конкретном сообщении: слежение за хвостом
            // выключаем, иначе первый же рост содержимого вернёт ленту вниз
            // и переход к сообщению отменится сам собой.
            followsTail = false
            userDrivesScroll = false
        }
    }

    /// Начал ли пользователь вести ленту сам.
    mutating func userStartedDriving() {
        userDrivesScroll = true
    }

    /// Пользователь отпустил ленту — фиксируем его намерение.
    ///
    /// Пока лентой не вёл никто (программная прокрутка), решение не
    /// меняется: иначе отправка сообщения или кнопка «вниз» гасили бы
    /// слежение из-за запоздалой геометрии.
    mutating func userStoppedDriving(nearBottom: Bool) {
        guard userDrivesScroll else { return }
        userDrivesScroll = false
        followsTail = nearBottom
    }

    /// Ленту повёл сам интерфейс — намерение пользователя это не отменяет.
    mutating func programmaticScroll() {
        userDrivesScroll = false
    }
}
