import Foundation

/// Кто в списке идёт корнем дерева задач.
///
/// Корнем идёт задача без родителя — и задача, чьего родителя нет в живом
/// наборе. Второе правило появилось из-за жалобы владельца 08.11.2026 («я вижу
/// только четыре задачи»): дочерняя задача, у которой родитель закрыт или
/// ушёл в архив, не имеет ряда, под которым её можно раскрыть, и раньше
/// пропадала из всех списков целиком.
enum TaskTreeVisibility {
    /// Корни — задача без родителя либо с родителем, которого нет среди живых.
    ///
    /// Принимает пары «id — родитель» для того набора карточек, который экран
    /// реально показывает. Считается по набору, а не по базе: если родитель
    /// отфильтрован (закрыт, архив, не проходит фильтр) — ребёнок становится
    /// корнем и остаётся видимым.
    static func visibleRootIDs(_ pairs: [(id: String, parentID: String?)]) -> Set<String> {
        guard !pairs.isEmpty else { return [] }
        let alive = Set(pairs.map(\.id))
        var roots = Set<String>()
        for pair in pairs {
            if let parent = pair.parentID, alive.contains(parent) { continue }
            roots.insert(pair.id)
        }
        return roots
    }
}
