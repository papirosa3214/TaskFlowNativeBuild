import Foundation

/// Правила применения ответа сервера к локальному кэшу задач.
///
/// Вынесены отдельным файлом без БД и без сети — только решения, — чтобы их
/// можно было проверить на macOS без симулятора (в файле нет ни GRDB, ни
/// URLSession).
///
/// Смысл правил — заметка «Кэш и синхронизация в мобильных клиентах»,
/// разбор «жёсткого рассинхрона» (п.1 и п.3 плана):
/// - отпечаток (ETag) — это «тело не менялось». Отпечаток без тела — враньё:
///   сервер ответит 304, а показать будет нечего, и список останется пустым
///   навсегда;
/// - курсор дельты — это «до этого места я догнал». Двинуть его раньше, чем
///   дельта применена, — значит потерять изменение навсегда.
enum TaskSyncCachePolicy {
    /// Отпечаток, который клиент отправляет серверу.
    ///
    /// Условие `If-None-Match` шлём ТОЛЬКО когда тело у нас действительно
    /// есть: иначе сервер ответит «не менялось» (304) на пустой кэш, и клиент
    /// останется без данных — отпечаток придётся сбросить и спросить заново.
    static func etagToSend(localHasBody: Bool, etag: String?) -> String? {
        guard localHasBody else { return nil }
        return etag
    }

    /// Тело надо запросить заново, без условия.
    ///
    /// 304 без тела в базе — отпечаток врёт: он записался раньше тела, база
    /// пересоздалась или тело записалось с ошибкой. Тогда отпечаток
    /// сбрасывается, и список запрашивается без условия.
    static func needsBodyRetry(notModified: Bool, localHasBody: Bool) -> Bool {
        notModified && !localHasBody
    }

    /// Дельту применена целиком — курсор можно двигать.
    ///
    /// Не хватает карточек (сеть отвалилась, часть запросов не прошла) —
    /// курсор остаётся на месте, и дельта повторится при следующем
    /// переподключении. Сдвинутый курсор при недо-применённой дельте
    /// означает потерянное изменение навсегда.
    static func canAdvanceCursor(appliedIds: Set<String>, requestedIds: [String]) -> Bool {
        Set(requestedIds).isSubset(of: appliedIds)
    }

    /// id карточек для батч-запроса: без повторов, с ограничением.
    ///
    /// Один запрос на всю дельту вместо запроса на каждую карточку по
    /// отдельности (после разрыва связи их набиралось до 60).
    static func batchRequestIds(changedIds: [String], limit: Int = 200) -> [String] {
        var out: [String] = []
        for id in changedIds {
            guard !id.isEmpty, !out.contains(id) else { continue }
            out.append(id)
            if out.count >= limit { break }
        }
        return out
    }

    /// Строки телефонной базы, которые пора удалить.
    ///
    /// Телефон хранит только ЖИВОЕ: всё, чего больше нет в живом списке
    /// (выполнено, отменено, ушло в архив, удалено), из базы уходит — на
    /// сервере оно лежит, а вторая копия на телефоне не нужна (владелец
    /// 02.11.2026).
    static func staleIds(stored: [String], live: Set<String>) -> [String] {
        stored.filter { !live.contains($0) }
    }
}
